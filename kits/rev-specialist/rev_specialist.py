# ============ Binary Patcher ============

def patch_binary(binary, offset, patch_type, length=16, target=None):
    """Patch binary di offset tertentu."""
    with open(binary, "rb") as f:
        data = bytearray(f.read())
    if offset >= len(data):
        print(f"[-] Offset 0x{offset:x} di luar file (size 0x{len(data):x})")
        return False
    if patch_type == "nop":
        data[offset:offset+length] = b"\\x90" * length
        print(f"[+] NOP sled @ 0x{offset:x}, len={length}")
    elif patch_type == "jump":
        if target is None:
            print("[-] Jump butuh --target")
            return False
        # x86_64: JMP rel32 (E9)
        if offset + 5 > len(data):
            print("[-] Offset terlalu dekat akhir file")
            return False
        rel32 = target - (offset + 5)
        data[offset] = 0xE9
        data[offset+1:offset+5] = struct.pack("<i", rel32)
        print(f"[+] JMP 0x{offset:x} -> 0x{target:x} (rel32={rel32})")
    elif patch_type == "shellcode":
        if target is None:
            print("[-] Shellcode butuh --target (file berisi shellcode)")
            return False
        with open(target, "rb") as f:
            shellcode = f.read()
        if offset + len(shellcode) > len(data):
            print("[-] Shellcode terlalu besar untuk area")
            return False
        data[offset:offset+len(shellcode)] = shellcode
        print(f"[+] Shellcode di-inject @ 0x{offset:x}, len={len(shellcode)}")
    else:
        print(f"[-] Patch type tidak dikenal: {patch_type}")
        return False
    # Write backup
    backup = binary + ".bak"
    with open(backup, "wb") as f:
        f.write(open(binary, "rb").read())
    with open(binary, "wb") as f:
        f.write(data)
    print(f"[+] Binary di-patch, backup: {backup}")
    return True

# ============ Protocol Analyzer ============

def protocol_analyzer(file_path, fields=None):
    """Analyze protocol/binary format dari capture."""
    with open(file_path, "rb") as f:
        data = f.read()
    print(f"[*] File: {file_path} ({len(data)} bytes)")
    print(f"[*] Hex dump (first 64 bytes):")
    for i in range(0, min(64, len(data)), 16):
        hex_part = " ".join(f"{b:02x}" for b in data[i:i+16])
        ascii_part = "".join(chr(b) if 32 <= b < 127 else "." for b in data[i:i+16])
        print(f"  {i:08x}: {hex_part:48} {ascii_part}")
    if fields:
        print(f"[*] Field parsing: {fields}")
        offset = 0
        for field in fields.split(","):
            field = field.strip()
            if field.startswith("4s"):
                val = data[offset:offset+4]
                print(f"  4s  @ 0x{offset:04x}: {val} (hex: {val.hex()})")
                offset += 4
            elif field.startswith("I"):
                if offset + 4 <= len(data):
                    val = struct.unpack("<I", data[offset:offset+4])[0]
                    print(f"  I   @ 0x{offset:04x}: {val} (0x{val:08x})")
                    offset += 4
            elif field.startswith("H"):
                if offset + 2 <= len(data):
                    val = struct.unpack("<H", data[offset:offset+2])[0]
                    print(f"  H   @ 0x{offset:04x}: {val} (0x{val:04x})")
                    offset += 2
            elif field.startswith("B"):
                if offset < len(data):
                    val = data[offset]
                    print(f"  B   @ 0x{offset:04x}: {val} (0x{val:02x})")
                    offset += 1
            elif field.startswith("8s"):
                val = data[offset:offset+8]
                print(f"  8s  @ 0x{offset:04x}: {val} (hex: {val.hex()})")
                offset += 8
            elif field.startswith("16s"):
                val = data[offset:offset+16]
                print(f"  16s @ 0x{offset:04x}: {val} (hex: {val.hex()})")
                offset += 16
            else:
                print(f"  [?] Unknown field: {field}")
                break

