#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""rev_toolkit.py — helper reverse engineering buat CTF.

Fitur:
  - strings: extract printable strings (min length configurable)
  - elf: parse ELF header (arch, endian, entry, sections)
  - patch: generate patch template (NOP sled, jump, shellcode placeholder)
  - r2gen: generate radare2 script untuk analisis otomatis
  - upx: detect UPX packing + unpack command

    python3 rev_toolkit.py strings <binary> [--min 6]
    python3 rev_toolkit.py elf <binary>
    python3 rev_toolkit.py patch --type nop --offset 0x400500 --len 16
    python3 rev_toolkit.py r2gen <binary> [--output script.r2]
    python3 rev_toolkit.py upx <binary>
"""
import argparse, os, re, struct, sys

def strings(binary: str, min_len: int = 4):
    with open(binary, "rb") as f:
        data = f.read()
    pattern = rb"[\x20-\x7e]{%d,}" % min_len
    results = []
    for m in re.finditer(pattern, data):
        results.append((m.start(), m.group().decode("ascii", errors="replace")))
    return results

def elf_info(binary: str):
    with open(binary, "rb") as f:
        data = f.read(64)
    if data[:4] != b"\x7fELF":
        return None
    ei_class = data[4]  # 1=32bit, 2=64bit
    ei_data = data[5]   # 1=LE, 2=BE
    is_64 = ei_class == 2
    is_le = ei_data == 1
    endian = "<" if is_le else ">"
    if is_64:
        e_type, e_machine = struct.unpack(endian + "HH", data[16:20])
        e_entry = struct.unpack(endian + "Q", data[24:32])[0]
        e_phoff = struct.unpack(endian + "Q", data[32:40])[0]
        e_shoff = struct.unpack(endian + "Q", data[40:48])[0]
        e_ehsize, e_phentsize, e_phnum = struct.unpack(endian + "HHH", data[52:58])
        e_shentsize, e_shnum, e_shstrndx = struct.unpack(endian + "HHH", data[58:64])
    else:
        e_type, e_machine = struct.unpack(endian + "HH", data[16:20])
        e_entry = struct.unpack(endian + "I", data[24:28])[0]
        e_phoff = struct.unpack(endian + "I", data[28:32])[0]
        e_shoff = struct.unpack(endian + "I", data[32:36])[0]
        e_ehsize, e_phentsize, e_phnum = struct.unpack(endian + "HHH", data[40:46])
        e_shentsize, e_shnum, e_shstrndx = struct.unpack(endian + "HHH", data[46:52])
    arch_map = {0x03: "x86", 0x3E: "x86_64", 0x28: "ARM", 0xB7: "AArch64", 0x08: "MIPS"}
    type_map = {1: "REL", 2: "EXEC", 3: "DYN", 4: "CORE"}
    arch = arch_map.get(e_machine, f"unknown(0x{e_machine:x})")
    etype = type_map.get(e_type, f"unknown(0x{e_type:x})")
    return {
        "class": "64-bit" if is_64 else "32-bit",
        "endian": "little" if is_le else "big",
        "type": etype,
        "arch": arch,
        "entry": f"0x{e_entry:x}",
        "phoff": e_phoff, "shoff": e_shoff,
        "phnum": e_phnum, "shnum": e_shnum,
    }

def patch_gen(patch_type: str, offset: int, length: int = 16):
    templates = {
        "nop": f"""# NOP sled @ 0x{offset:x}, len={length}
# Original bytes di-overwrite dengen 0x90
# Gunakan: objdump -d binary | grep -A5 0x{offset:x}
# Patch dengan: printf '\\x90\\x90...' | dd of=binary bs=1 seek={offset} conv=notrunc
""",
        "jump": f"""# JMP/CALL redirect @ 0x{offset:x}
# x86_64: E9 <rel32>  (jmp rel32)
# x86:    E9 <rel32>
# Hitung: rel32 = target - (offset + 5)
""",
        "shellcode": f"""# Shellcode placeholder @ 0x{offset:x}, len={length}
# x86_64 execve("/bin/sh"):
#   48 31 f6 48 31 d2 48 31 c0 48 89 c7 48 8d 35 11 00 00 00
#   b0 3b 0f 05
# x86 execve("/bin/sh"):
#   31 c0 50 68 2f 2f 73 68 68 2f 62 69 6e 89 e3 50 53 89 e1
#   b0 0b cd 80
""",
    }
    return templates.get(patch_type, "Unknown patch type")

def r2gen(binary: str, output: str = None):
    script = f"""# radare2 auto-analysis script
# Generated by rev-toolkit
# Usage: r2 -i {output or 'script.r2'} {binary}

# Analisis dasar
aaa
afl          # list functions
s main       # seek to main
pdf          # disasm main
VV           # graph mode

# Cari string menarik
iz~?         # list strings
izz~flag     # cari flag
izz~password # cari password
izz~secret   # cari secret

# Cek proteksi
iI           # info binary
iR           # relro
iN           # nx
iS           # canary

# Export
# afvn old_name new_name  # rename variable
"""
    if output:
        with open(output, "w") as f:
            f.write(script)
        print(f"[+] r2 script ditulis ke {output}")
    else:
        print(script)

def upx_check(binary: str):
    with open(binary, "rb") as f:
        data = f.read()
    if b"UPX!" in data or b"UPX0" in data or b"UPX1" in data:
        print("[!] Binary terdeteksi UPX packed")
        print("[*] Unpack: upx -d", binary)
        print("[*] Force:  upx -d -f", binary)
        return True
    print("[*] Tidak terdeteksi UPX packing")
    return False

def main():
    args = sys.argv[1:]
    if not args:
        print(__doc__)
        return
    cmd = args[0]
    if cmd == "strings":
        if len(args) < 2:
            print("Usage: rev_toolkit.py strings <binary> [--min N]")
            return
        binary = args[1]
        min_len = 4
        if "--min" in args:
            min_len = int(args[args.index("--min") + 1])
        results = strings(binary, min_len)
        for offset, s in results:
            print(f"0x{offset:08x}: {s}")
        print(f"\n[*] Total: {len(results)} strings")
    elif cmd == "elf":
        if len(args) < 2:
            print("Usage: rev_toolkit.py elf <binary>")
            return
        info = elf_info(args[1])
        if not info:
            print("[-] Bukan ELF valid")
            return
        for k, v in info.items():
            print(f"  {k:12}: {v}")
    elif cmd == "patch":
        p = argparse.ArgumentParser()
        p.add_argument("--type", required=True, choices=["nop", "jump", "shellcode"])
        p.add_argument("--offset", type=lambda x: int(x, 0), required=True)
        p.add_argument("--len", type=int, default=16)
        a = p.parse_args(args[1:])
        print(patch_gen(a.type, a.offset, a.len))
    elif cmd == "r2gen":
        if len(args) < 2:
            print("Usage: rev_toolkit.py r2gen <binary> [--output script.r2]")
            return
        binary = args[1]
        output = None
        if "--output" in args:
            output = args[args.index("--output") + 1]
        r2gen(binary, output)
    elif cmd == "upx":
        if len(args) < 2:
            print("Usage: rev_toolkit.py upx <binary>")
            return
        upx_check(args[1])
    else:
        print(__doc__)

if __name__ == "__main__":
    main()
